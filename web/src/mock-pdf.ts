/**
 * 极小的多页 PDF 生成器（只给 VITE_MOCK 用）：让 <embed type="application/pdf"> 在浏览器里
 * 真的能渲染出 N 页，从而演示 "#page=42" 的跳页。
 *
 * 只用 ASCII（/Length 与 UTF-8 字节数一致），xref 偏移按对象实际起始字节计算。
 */
export function buildPdf(pageCount: number): Uint8Array {
  const total = Math.max(1, Math.min(Math.floor(pageCount) || 1, 300));
  const encoder = new TextEncoder();
  const chunks: Uint8Array[] = [];
  const offsets: number[] = [];
  let length = 0;

  const push = (text: string): void => {
    const bytes = encoder.encode(text);
    chunks.push(bytes);
    length += bytes.length;
  };
  const pushObject = (id: number, body: string): void => {
    offsets[id] = length;
    push(`${id} 0 obj\n${body}\nendobj\n`);
  };

  const pageIds = Array.from({ length: total }, (_, i) => 3 + i);
  const contentIds = Array.from({ length: total }, (_, i) => 3 + total + i);
  const fontId = 3 + 2 * total;
  const objectCount = fontId;

  push("%PDF-1.4\n");
  pushObject(1, "<< /Type /Catalog /Pages 2 0 R >>");
  pushObject(
    2,
    `<< /Type /Pages /Kids [${pageIds.map((id) => `${id} 0 R`).join(" ")}] /Count ${total} >>`,
  );

  for (let i = 0; i < total; i += 1) {
    pushObject(
      pageIds[i],
      `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 ${fontId} 0 R >> >> /Contents ${contentIds[i]} 0 R >>`,
    );
  }

  for (let i = 0; i < total; i += 1) {
    const page = i + 1;
    const content =
      `BT /F1 22 Tf 64 760 Td (MISAKA mock PDF) Tj ET\n` +
      `BT /F1 16 Tf 64 730 Td (page ${page} of ${total}) Tj ET\n` +
      `BT /F1 11 Tf 64 700 Td (doc:atlas#p${page}  -  generated by web/src/mock-pdf.ts) Tj ET\n`;
    pushObject(contentIds[i], `<< /Length ${content.length} >>\nstream\n${content}endstream`);
  }

  pushObject(fontId, "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>");

  const xrefOffset = length;
  const entries = ["0000000000 65535 f \n"];
  for (let id = 1; id <= objectCount; id += 1) {
    entries.push(`${String(offsets[id] ?? 0).padStart(10, "0")} 00000 n \n`);
  }
  push(
    `xref\n0 ${objectCount + 1}\n${entries.join("")}trailer\n<< /Size ${objectCount + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF\n`,
  );

  const bytes = new Uint8Array(length);
  let cursor = 0;
  for (const chunk of chunks) {
    bytes.set(chunk, cursor);
    cursor += chunk.length;
  }
  return bytes;
}
